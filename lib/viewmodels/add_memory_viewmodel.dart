import 'package:flutter/foundation.dart' show ChangeNotifier, kIsWeb;
import 'package:image_picker/image_picker.dart';
import '../models/memory.dart';

/// ViewModel for adding a new memory
/// Follows MVVM pattern - handles form state and memory creation logic
class AddMemoryViewModel extends ChangeNotifier {
  final ImagePicker _picker = ImagePicker();

  String _step = 'choose'; // 'choose' or 'details'
  String _photoUrl = '';
  XFile? _pickedFile;
  String _title = '';
  String _note = '';
  String _emoji = '';

  // Map position when pin was added
  double _mapX = 50.0; // Percentage (0-100) - for UI positioning
  double _mapY = 50.0; // Percentage (0-100) - for UI positioning
  double? _actualLat; // Actual GPS latitude
  double? _actualLng; // Actual GPS longitude

  // Getters
  String get step => _step;
  String get photoUrl => _photoUrl;
  XFile? get pickedFile => _pickedFile;
  String get title => _title;
  String get note => _note;
  String get emoji => _emoji;
  double get mapX => _mapX;
  double get mapY => _mapY;
  double? get actualLat => _actualLat;
  double? get actualLng => _actualLng;

  /// Set map position (called when user clicks add pin button)
  /// This sets the percentage position for UI
  void setMapPosition(double x, double y) {
    _mapX = x.clamp(0.0, 100.0);
    _mapY = y.clamp(0.0, 100.0);
  }

  /// Set actual GPS coordinates (called when user taps on map)
  void setActualCoordinates(double lat, double lng) {
    _actualLat = lat;
    _actualLng = lng;

    // Also update percentage position for UI consistency
    _mapX = ((lng + 180) / 360 * 100).clamp(0.0, 100.0);
    _mapY = ((90 - lat) / 180 * 100).clamp(0.0, 100.0);

    notifyListeners();
  }

  /// Set title
  void setTitle(String title) {
    _title = title;
    notifyListeners();
  }

  /// Set note
  void setNote(String note) {
    _note = note;
    notifyListeners();
  }

  /// Set emoji
  void setEmoji(String emoji) {
    _emoji = emoji;
    notifyListeners();
  }

  /// Handle photo capture from camera
  /// Returns true if camera screen should be opened, false if image was captured directly
  Future<bool> handlePhotoCapture() async {
    // For web, use image_picker which supports camera through browser API
    // The browser will prompt for camera permission if needed
    // For mobile, try image_picker first, fall back to camera screen if needed
    try {
      final XFile? image = await _picker.pickImage(
        source: ImageSource.camera,
        maxWidth: 1920,
        maxHeight: 1920,
        imageQuality: 85,
      );

      if (image != null) {
        _pickedFile = image;
        // For web, image.path is a data URL; for mobile it's a file path
        _photoUrl = image.path;
        _step = 'details';
        notifyListeners();
        return false; // Image captured, no need for camera screen
      }
      // User cancelled the camera picker
      return false; // Don't try to open camera screen if user cancelled
    } catch (e) {
      // If image_picker fails, log the error
      // On web: camera access might be denied or not available
      // On mobile: fall back to camera screen
      if (kIsWeb) {
        // On web, if camera access fails, we can't use camera screen (not supported)
        // The error will be handled by the UI layer
        return false;
      }
      // For mobile, fall back to camera screen
      return true;
    }
  }

  /// Set captured image from camera screen
  void setCapturedImage(String imagePath, XFile? file) {
    _pickedFile = file;
    _photoUrl = imagePath;
    _step = 'details';
    notifyListeners();
  }

  /// Handle photo selection from gallery
  Future<void> handlePhotoFromGallery() async {
    try {
      final XFile? image = await _picker.pickImage(
        source: ImageSource.gallery,
        maxWidth: 1920,
        maxHeight: 1920,
        imageQuality: 85,
      );

      if (image != null) {
        _pickedFile = image;
        // For web, create object URL; for mobile use file path
        if (kIsWeb) {
          _photoUrl = image.path; // Web returns data URL
        } else {
          _photoUrl = image.path; // Mobile returns file path
        }
        _step = 'details';
        notifyListeners();
      }
    } catch (e) {
      // Handle error - could notify user
    }
  }

  /// Skip photo
  void skipPhoto() {
    _photoUrl = '';
    _step = 'details';
    notifyListeners();
  }

  /// Go back to choose step
  void goBackToChoose() {
    _step = 'choose';
    _photoUrl = '';
    notifyListeners();
  }

  /// Create memory from current form data
  /// Note: id will be auto-generated by Firestore, but we need a placeholder
  /// photoUrl is set directly from the image picker (blob URL or data URL on web)
  Memory? createMemory() {
    if (_title.isEmpty) {
      return null; // Title is required
    }

    // Use actual GPS coordinates if available, otherwise calculate from map position
    double lat, lng;
    if (_actualLat != null && _actualLng != null) {
      // Use actual GPS coordinates from map tap
      lat = _actualLat!;
      lng = _actualLng!;
    } else {
      // Fallback: Convert percentage position (0-100) to lat/lng
      // X: 0-100 maps to lng: -180 to 180
      // Y: 0-100 maps to lat: 90 to -90 (inverted because screen Y increases downward)
      lng = ((_mapX / 100.0) * 360.0 - 180.0);
      lat = (90.0 - (_mapY / 100.0) * 180.0); // Inverted
    }

    return Memory(
      id: '', // Will be set by Firestore service when adding
      title: _title,
      note: _note.isNotEmpty ? _note : null,
      photoUrl: _photoUrl.isNotEmpty ? _photoUrl : null,
      emoji: _emoji.isNotEmpty ? _emoji : null,
      isStarred: false,
      coordinates: MemoryCoordinates(
        x: _mapX,
        y: _mapY,
        lat: lat.toStringAsFixed(6),
        lng: lng.toStringAsFixed(6),
      ),
      timestamp: DateTime.now(), // Auto-set to current time
    );
  }

  /// Reset form
  void reset() {
    _step = 'choose';
    _photoUrl = '';
    _pickedFile = null;
    _title = '';
    _note = '';
    _emoji = '';
    _actualLat = null;
    _actualLng = null;
    notifyListeners();
  }
}
